#!/usr/bin/env node
/**
 * Bundles the whole tool into one self-contained HTML file.
 *
 * The knowledge base, the retrieval engine and the UI all get inlined, so the
 * result runs from a file:// URL, a static host, or anywhere a single HTML file
 * can go. There is no server and therefore no AI synthesis - the page answers
 * from the knowledge base the same way the server does when no key is set.
 *
 *   node scripts/build-standalone.mjs            -> dist/procurement-navigator.html
 *   node scripts/build-standalone.mjs --fragment -> also writes dist/artifact.html
 *                                                   (no <html>/<head>/<body>, for
 *                                                   hosts that supply their own shell)
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEFAULT_FALLBACKS } from '../server/groq.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (...p) => readFileSync(join(root, ...p), 'utf8');

const kb = JSON.parse(read('data', 'knowledge-base.json'));
const css = read('public', 'styles.css');
const shell = read('public', 'index.html');
const app = read('public', 'app.js');

/**
 * ES modules cannot run from a plain <script>; strip the module syntax.
 * Note the optional `async` - missing it once shipped a bundle that died on
 * `export async function` before any of the app ran.
 */
const asClassicScript = (source) =>
  source
    .replace(/^export\s+(?=(?:async\s+)?(?:class|function|const|let|var)\b)/gm, '')
    .replace(/^export\s*\{[^}]*\}\s*;?\s*$/gm, '')
    .replace(/^export\s+default\s+/gm, '')
    .replace(/^import\s[^;]+;\s*$/gm, '');

/** Any surviving module keyword is a syntax error the moment the page loads. */
function assertNoModuleSyntax(source, label) {
  const leftovers = source
    .split('\n')
    .map((line, i) => ({ line: line.trim(), n: i + 1 }))
    .filter(({ line }) => /^(export|import)\b/.test(line));
  if (leftovers.length) {
    throw new Error(
      `${label} still contains module syntax that would break the bundle:\n` +
        leftovers.map(({ n, line }) => `  line ${n}: ${line.slice(0, 90)}`).join('\n')
    );
  }
}

const engine = ['retrieval', 'compose', 'prompt', 'guardrails', 'groq', 'answer']
  .map((name) => {
    const converted = asClassicScript(read('server', `${name}.js`));
    assertNoModuleSyntax(converted, `server/${name}.js`);
    return `/* ── server/${name}.js ─────────────────────────── */\n${converted}`;
  })
  .join('\n');

// AI in the browser is opt-in and the key ends up readable in the published
// page. Only inject it when the build is explicitly asked to.
const embedKey = process.argv.includes('--embed-key');
const apiKey = embedKey ? (process.env.GROQ_API_KEY || '').trim() : '';
if (embedKey && !apiKey) {
  throw new Error('--embed-key was passed but GROQ_API_KEY is empty');
}
const aiConfig = apiKey
  ? {
      apiKey,
      model: process.env.GROQ_MODEL || 'llama-3.3-70b-versatile',
      // Falls back to the chain in server/groq.js when unset, so a model
      // retirement does not require editing the build.
      fallbackModels: (process.env.GROQ_FALLBACK_MODELS || DEFAULT_FALLBACKS.join(','))
        .split(',').map((m) => m.trim()).filter(Boolean),
      endpoint: process.env.GROQ_ENDPOINT || 'https://api.groq.com/openai/v1/chat/completions',
    }
  : null;

// Pull the page content out of the shell, dropping the tags that referenced
// external files - everything is inline now.
const body = shell
  .slice(shell.indexOf('<body>') + '<body>'.length, shell.lastIndexOf('</body>'))
  .replace(/<script src="\/app\.js"><\/script>/, '')
  .trim();

// Match the whole tag, allowing quoted attribute values that legitimately
// contain '>' (a data: URI can). A naive [^>]* truncates the tag mid-attribute,
// leaving an unterminated quote that swallows everything after it - including
// the stylesheet.
const favicon = shell.match(/<link\s+rel="icon"(?:[^>"']|"[^"]*"|'[^']*')*>/)?.[0] ?? '';
if (!favicon) throw new Error('Could not find the favicon link in public/index.html');

// `</script>` anywhere inside the JSON would close the tag early.
const kbLiteral = JSON.stringify(kb).replace(/</g, '\\u003c');

const scripts = `
<script>
window.__PN_STANDALONE__ = true;
const KB = ${kbLiteral};
</script>
<script>
${engine}
window.__PN_EMBEDDED__ = {
  kb: KB,
  Answerer,
  ai: ${aiConfig ? JSON.stringify(aiConfig) : 'null'},
};
</script>
<script>
${app}
</script>`.trim();

const banner = `<!-- NSW Procurement Navigator ${kb.meta.version} - standalone build
     ${kb.meta.chunk_count} sections across ${kb.meta.topic_count} topics.
     AI answering: ${aiConfig ? 'enabled, API key embedded below and readable by anyone' : 'disabled'}.
     Generated by scripts/build-standalone.mjs from data/knowledge-base.json.
     Edit the sources, not this file. -->`;

const title = 'NSW Procurement Navigator';
const description =
  'Plain-English answers on NSW procurement for councils, government agencies, suppliers and the public.';

// Head content is identical in both outputs; only the document skeleton differs.
// Artifact hosts supply their own <html>/<head>/<body>, so the fragment omits them.
const head = `<title>${title}</title>
<meta name="description" content="${description}">
${favicon}
<style>
${css}
</style>`;

const fragment = `${banner}
${head}
${body}
${scripts}
`;

const full = `<!doctype html>
<html lang="en-AU">
<head>
${banner}
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
${head}
</head>
<body>
${body}
${scripts}
</body>
</html>
`;

// A bundle whose <style> was destroyed still has every element in place, so
// element counts pass while the page renders as raw text. Check the markup
// itself before writing anything.
function assertRenderable(html, label) {
  const problems = [];
  const headEnd = html.indexOf('</head>');
  const styleOpen = html.indexOf('<style>');
  if (styleOpen === -1) problems.push('no <style> element');
  if (headEnd !== -1 && styleOpen > headEnd) problems.push('<style> is outside <head>');
  if ((html.match(/<style>/g) || []).length !== 1) problems.push('expected exactly one <style>');
  if ((html.match(/<\/style>/g) || []).length !== 1) problems.push('expected exactly one </style>');

  const preamble = html.slice(0, styleOpen === -1 ? 0 : styleOpen);
  if ((preamble.match(/"/g) || []).length % 2 !== 0) {
    problems.push('unbalanced double quote before <style> - a tag is swallowing it');
  }

  if (problems.length) throw new Error(`${label} would not render: ${problems.join('; ')}`);
}

mkdirSync(join(root, 'dist'), { recursive: true });

const outFull = join(root, 'dist', 'procurement-navigator.html');
assertRenderable(full, 'dist/procurement-navigator.html');
writeFileSync(outFull, full);
report(outFull);

if (process.argv.includes('--fragment')) {
  const outFragment = join(root, 'dist', 'artifact.html');
  assertRenderable(fragment, 'dist/artifact.html');
  writeFileSync(outFragment, fragment);
  report(outFragment);
}

if (aiConfig) {
  console.warn(
    'WARNING: the Groq API key is embedded in this build and is readable by anyone\n' +
      '         who opens the page. It cannot be rate limited. Rotate it if it leaks.'
  );
}

function report(path) {
  const kbBytes = Buffer.byteLength(readFileSync(path));
  console.log(`Wrote ${path.replace(root + '/', '')} (${(kbBytes / 1024).toFixed(0)} KB)`);
}
